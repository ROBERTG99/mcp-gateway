// FileSHA256 returns the hex SHA-256 of a file (prompt_hashes of detector pattern files).
func FileSHA256(path string) (string, error) {
	b, err := os.ReadFile(path) //nolint:gosec // G304: repository paths
	if err != nil {
		return "", fmt.Errorf("hash %s: %w", path, err)
	}
	sum := sha256.Sum256(b)
	return hex.EncodeToString(sum[:]), nil
}

// ReportFile names a suite's report: <suite>.json for the gated test split, <suite>.dev.json for dev.
func ReportFile(suite, split string) string {
	if split == "test" {
		return suite + ".json"
	}
	return suite + "." + split + ".json"
}

// WriteReport writes r as indented JSON.
func WriteReport(dir string, r Report, split string) error {
	b, err := json.MarshalIndent(r, "", "  ")
	if err != nil {
		return fmt.Errorf("encode report: %w", err)
	}
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return fmt.Errorf("create %s: %w", dir, err)
	}
	path := filepath.Join(dir, ReportFile(r.Suite, split))
	if err := os.WriteFile(path, append(b, '\n'), 0o600); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	return nil
}

// ReadReport reads one report; a missing file returns (nil, nil).
func ReadReport(path string) (*Report, error) {
	b, err := os.ReadFile(path) //nolint:gosec // G304: repository paths
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", path, err)
	}
	var r Report
	if err := json.Unmarshal(b, &r); err != nil {
		return nil, fmt.Errorf("decode %s: %w", path, err)
	}
	return &r, nil
}

// Suites is the order of suites in REPORT.md.
var Suites = []string{"policy.v1", "injection.v1", "redaction.v1", "chaos.v1", LatencySuite}

// Markdown renders evals/REPORT.md from the reports in reportsDir and the baselines in
// baselineDir. Every number comes from a report file; nothing is typed by hand.
func Markdown(reportsDir, baselineDir string) (string, error) {
	var b strings.Builder
	b.WriteString("# Eval report\n\n")
	b.WriteString("Generated by `make eval` (`go run ./cmd/evalgen run`) from `evals/reports/*.json`; do not edit by hand. ")
	b.WriteString("Gated numbers are on the test partition; thresholds were tuned on dev only. Mode `offline`, models: none (no model is called). ")
	b.WriteString("Confidence intervals are 95% percentile bootstrap over cases (2,000 resamples, seed 1337).\n\n")
	b.WriteString("| Suite | Metric | Test value | 95% CI | Threshold | Passed | Dev value | Baseline | Delta (pp) |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|---|\n")
	var meta *Report
	missing := []string{}
	for _, suite := range Suites {
		test, err := ReadReport(filepath.Join(reportsDir, ReportFile(suite, "test")))
		if err != nil {
			return "", err
		}
		if test == nil {
			missing = append(missing, suite)
			continue
		}
		if meta == nil {
			meta = test
		}
		dev, err := ReadReport(filepath.Join(reportsDir, ReportFile(suite, "dev")))
		if err != nil {
			return "", err
		}
		base, err := ReadReport(filepath.Join(baselineDir, ReportFile(suite, "test")))
		if err != nil {
			return "", err
		}
		names := make([]string, 0, len(test.Metrics))
		for n := range test.Metrics {
			names = append(names, n)
		}
		slices.Sort(names)
		for _, n := range names {
			m := test.Metrics[n]
			cmp := "≥"
			if m.Direction == Lower {
				cmp = "≤"
			}
			if strings.HasSuffix(n, "_ms") && m.Direction == Lower {
				cmp = "<"
			}
			passed := "yes"
			if !m.Passed {
				passed = "**no**"
			}
			devV, baseV, delta := "—", "—", "—"
			if dev != nil {
				if dm, ok := dev.Metrics[n]; ok {
					devV = num(dm.Value)
				}
			}
			if base != nil {
				if bm, ok := base.Metrics[n]; ok {
					baseV = num(bm.Value)
					if !strings.HasSuffix(n, "_ms") {
						delta = fmt.Sprintf("%+.1f", (m.Value-bm.Value)*100)
					}
				}
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s | [%s, %s] | %s %s | %s | %s | %s | %s |\n", suite, n, num(m.Value), num(m.CILow), num(m.CIHigh),
				cmp, num(m.Threshold), passed, devV, baseV, delta)
		}
	}
	if meta != nil {
		fmt.Fprintf(&b, "\nGit SHA `%s`, created %s. Prompt hashes (SHA-256):\n\n", meta.GitSHA, meta.CreatedAt)
		keys := make([]string, 0, len(meta.PromptHashes))
		for k := range meta.PromptHashes {
			keys = append(keys, k)
		}
		slices.Sort(keys)
		for _, k := range keys {
			fmt.Fprintf(&b, "- `%s`: `%s`\n", k, meta.PromptHashes[k])
		}
	}
	if len(missing) > 0 {
		fmt.Fprintf(&b, "\nNot run in this report: %s.\n", strings.Join(missing, ", "))
	}
	b.WriteString("\nInjection scoring is defence in depth, not a solution: see `docs/evaluation.md`.\n")
	return b.String(), nil
}

func num(f float64) string {
	s := fmt.Sprintf("%.4f", f)
	s = strings.TrimRight(strings.TrimRight(s, "0"), ".")
	if s == "" || s == "-" {
		return "0"
	}
	return s
}
