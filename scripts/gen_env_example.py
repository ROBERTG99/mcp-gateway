#!/usr/bin/env python3
"""Regenerate .env.example from the struct tags in internal/config/config.go plus non-gateway variables."""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIELD = re.compile(
    r'env:"(MCPGW_[A-Z0-9_]+)" default:"([^"]*)"(?: oneof:"([^"]*)")?(?: secret:"true")? desc:"([^"]*)"'
)
DEV_VALUES = {  # development values for the compose stack (synthetic, never real secrets)
    "MCPGW_APP_DB_PASSWORD": "mcpgw_app",
    "MCPGW_READONLY_DB_PASSWORD": "mcpgw_readonly",
    "MCPGW_UPSTREAM_DB_PASSWORD": "mcpgw_upstream",
    "MCPGW_APPROVAL_WEBHOOK_SECRET": "dev-webhook-secret-change-me",
}
EXTRA = """
# ---- Example upstreams (upstream-ledger, upstream-crm, upstream-orders) ----
# Listen address of an example upstream
MCPGW_UPSTREAM_ADDR=:8213
# Postgres URL used by the example upstreams (role mcpgw_upstream)
MCPGW_UPSTREAM_DATABASE_URL=postgres://mcpgw_upstream:mcpgw_upstream@localhost:8220/mcpgw?sslmode=disable
# Chaos: fraction of refund keys whose transaction stalls past the gateway timeout (0..1)
MCPGW_FAULT_TIMEOUT_RATE=0
# Chaos: stall duration for injected timeouts
MCPGW_FAULT_STALL=12s
# Demo: refund keys with this prefix stall mid-call (step 4 of make demo); empty disables
MCPGW_FAULT_STALL_KEY_PREFIX=

# ---- Clients and tools (demo-agent, loadgen, evalgen, make dev-token) ----
# Gateway MCP endpoint used by clients
MCPGW_GATEWAY_URL=http://localhost:8210/mcp
# Admin API base URL used by clients
MCPGW_ADMIN_URL=http://localhost:8200
# Bearer token for clients and .mcp.json (mint with make dev-token)
MCPGW_DEV_TOKEN=

# ---- Tests ----
# Use the running compose services instead of testcontainers in integration tests (1 to enable)
MCPGW_TEST_USE_COMPOSE=0
# Postgres superuser URL for integration tests (compose mode)
MCPGW_TEST_DATABASE_URL=postgres://postgres:postgres@localhost:8220/postgres?sslmode=disable
# Redis URL for integration tests (compose mode)
MCPGW_TEST_REDIS_URL=redis://localhost:8230/15
# DynamoDB endpoint for integration tests (compose mode)
MCPGW_TEST_DYNAMODB_ENDPOINT=http://localhost:8240

# ---- Evals ----
# Budget for make eval-live (no model is called here: estimated cost USD 0.00)
LIVE_EVAL_BUDGET_USD=2
"""


def main() -> None:
    src = (ROOT / "internal" / "config" / "config.go").read_text(encoding="utf-8")
    lines = [
        "# mcp-gateway environment variables. Copy to .env (`make bootstrap` does it) and adjust.",
        "# Generated by scripts/gen_env_example.py from internal/config/config.go; edit the struct tags.",
        "# Synthetic development values only. Never commit real secrets.",
        "",
        "# ---- Gateway (mcp-gateway serve, migrate, dev-issuer) ----",
    ]
    for name, default, oneof, desc in FIELD.findall(src):
        extra = f" ({oneof.replace(',', ' | ')})" if oneof else ""
        lines.append(f"# {desc}{extra}")
        lines.append(f"{name}={DEV_VALUES.get(name, default)}")
    (ROOT / ".env.example").write_text("\n".join(lines) + "\n" + EXTRA, encoding="utf-8")


if __name__ == "__main__":
    main()
